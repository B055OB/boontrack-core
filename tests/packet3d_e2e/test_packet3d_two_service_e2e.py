def test_core_migration_037_zero_orders_ddl():
    """Migration 037 must contain ZERO DDL statements against Inbox-owned public.orders."""
    sql = MIGRATION_037_PATH.read_text(encoding="utf-8")
    sql_no_comments = "\n".join(line for line in sql.splitlines() if not line.strip().startswith("--"))
    upper = sql_no_comments.upper()
    assert "ALTER TABLE PUBLIC.ORDERS" not in upper
    assert "ALTER TABLE ORDERS" not in upper
    assert "CREATE TABLE PUBLIC.ORDERS" not in upper
    assert "DROP TABLE PUBLIC.ORDERS" not in upper


